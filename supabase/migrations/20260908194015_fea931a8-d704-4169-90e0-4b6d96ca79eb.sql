ALTER TABLE public.profiles REPLICA IDENTITY FULL;
ALTER TABLE public.directory_permissions REPLICA IDENTITY FULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'profiles'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.profiles;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'directory_permissions'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.directory_permissions;
  END IF;
END $$;